#[test]
fn package_license_file_must_be_canonical_text_not_merely_present() {
    let root = git_fixture("package-license");
    let canonical =
        fs::read(concat!(env!("CARGO_MANIFEST_DIR"), "/LICENSE")).expect("repo LICENSE exists");

    // A declared `license-file` key naming a missing target does not count.
    write(
        &root,
        "crates/declared-missing/Cargo.toml",
        "[package]\nname = \"declared-missing\"\nversion = \"0.1.0\"\nlicense-file = \"LICENSE\"\n",
    );

    // A declared `license-file` key naming a real but non-canonical file
    // does not count either -- the key existing is not the same as the
    // license text actually being there.
    write(
        &root,
        "crates/declared-wrong/Cargo.toml",
        "[package]\nname = \"declared-wrong\"\nversion = \"0.1.0\"\nlicense-file = \"LICENSE\"\n",
    );
    write(&root, "crates/declared-wrong/LICENSE", "not the MPL text\n");

    // A `LICENSE`-prefixed directory entry with the wrong content does not
    // satisfy the convention-based (no `license-file` key) path either.
    write(
        &root,
        "crates/conventional-wrong/Cargo.toml",
        "[package]\nname = \"conventional-wrong\"\nversion = \"0.1.0\"\n",
    );
    write(
        &root,
        "crates/conventional-wrong/LICENSE",
        "not the MPL text\n",
    );

    // The real, canonical byte-identical text satisfies both paths.
    write(
        &root,
        "crates/declared-real/Cargo.toml",
        "[package]\nname = \"declared-real\"\nversion = \"0.1.0\"\nlicense-file = \"LICENSE\"\n",
    );
    fs::write(root.join("crates/declared-real/LICENSE"), &canonical).unwrap();
    write(
        &root,
        "crates/conventional-real/Cargo.toml",
        "[package]\nname = \"conventional-real\"\nversion = \"0.1.0\"\n",
    );
    fs::write(root.join("crates/conventional-real/LICENSE"), &canonical).unwrap();

    let mut missing = packages_without_license(&root).unwrap();
    missing.sort();
    assert_eq!(
        missing,
        [
            "crates/conventional-wrong/Cargo.toml",
            "crates/declared-missing/Cargo.toml",
            "crates/declared-wrong/Cargo.toml",
        ]
    );
}

#[test]
fn publish_and_license_file_resolve_through_workspace_inheritance() {
    let root = git_fixture("workspace-inheritance");
    let canonical =
        fs::read(concat!(env!("CARGO_MANIFEST_DIR"), "/LICENSE")).expect("repo LICENSE exists");

    write(
        &root,
        "Cargo.toml",
        "[workspace]\nmembers = []\n\n\
         [workspace.package]\n\
         license-file = \"LICENSE\"\n\
         publish = false\n",
    );
    fs::write(root.join("LICENSE"), &canonical).unwrap();

    // `publish.workspace = true` inheriting `false` must be skipped exactly
    // like a direct `publish = false` -- not silently treated as publishable
    // because the value isn't a plain boolean in this package's own table.
    // This crate has no license text at all, so if inheritance were not
    // resolved it would wrongly appear as missing.
    write(
        &root,
        "crates/inherits-unpublished/Cargo.toml",
        "[package]\nname = \"inherits-unpublished\"\nversion = \"0.1.0\"\npublish.workspace = true\n",
    );

    // `license-file.workspace = true` resolves the workspace's declared
    // path relative to the WORKSPACE root, not this package's own
    // directory -- this crate carries no local LICENSE file at all, and is
    // itself publishable (default), so it must resolve through inheritance
    // to be recognized as carrying a license.
    write(
        &root,
        "crates/inherits-license/Cargo.toml",
        "[package]\nname = \"inherits-license\"\nversion = \"0.1.0\"\nlicense-file.workspace = true\n",
    );

    let missing = packages_without_license(&root).unwrap();
    assert_eq!(missing, Vec::<String>::new());
}

#[test]
fn license_file_workspace_inheritance_resolves_through_the_nearest_enclosing_workspace() {
    let root = git_fixture("nested-workspace");
    let canonical =
        fs::read(concat!(env!("CARGO_MANIFEST_DIR"), "/LICENSE")).expect("repo LICENSE exists");

    // The checkout root's own workspace declares an inherited path that
    // does NOT exist -- if this were (wrongly) used for a package under
    // crates/, it would be rejected.
    write(
        &root,
        "Cargo.toml",
        "[workspace]\nmembers = []\n\n[workspace.package]\nlicense-file = \"NOWHERE\"\n",
    );

    // A SEPARATE, real, nested workspace at crates/Cargo.toml (matching
    // this repository's own actual structure) declares its own inherited
    // path, which DOES exist relative to ITS root (crates/LICENSE, not the
    // checkout root's LICENSE).
    write(
        &root,
        "crates/Cargo.toml",
        "[workspace]\nmembers = [\"member\"]\n\n[workspace.package]\nlicense-file = \"LICENSE\"\n",
    );
    fs::write(root.join("crates/LICENSE"), &canonical).unwrap();
    write(
        &root,
        "crates/member/Cargo.toml",
        "[package]\nname = \"member\"\nversion = \"0.1.0\"\nlicense-file.workspace = true\n",
    );

    let missing = packages_without_license(&root).unwrap();
    assert_eq!(missing, Vec::<String>::new());
}

#[test]
fn an_explicit_package_workspace_override_takes_precedence_over_ancestor_discovery() {
    let root = git_fixture("workspace-override");
    let canonical =
        fs::read(concat!(env!("CARGO_MANIFEST_DIR"), "/LICENSE")).expect("repo LICENSE exists");

    // The nearest ANCESTOR workspace (what plain directory-walking would
    // find) declares an inherited path that does NOT exist -- if this were
    // used instead of the explicit override below, it would be rejected.
    write(
        &root,
        "crates/Cargo.toml",
        "[workspace]\nmembers = []\n\n[workspace.package]\nlicense-file = \"NOWHERE\"\n",
    );

    // The package explicitly names a DIFFERENT real workspace via
    // `workspace = "path"` (relative to the package's own directory),
    // matching Cargo's own override precedence -- this one's inherited
    // path does exist, relative to ITS root.
    write(
        &root,
        "elsewhere/Cargo.toml",
        "[workspace]\nmembers = []\n\n[workspace.package]\nlicense-file = \"LICENSE\"\n",
    );
    fs::write(root.join("elsewhere/LICENSE"), &canonical).unwrap();
    write(
        &root,
        "crates/member/Cargo.toml",
        "[package]\nname = \"member\"\nversion = \"0.1.0\"\nworkspace = \"../../elsewhere\"\nlicense-file.workspace = true\n",
    );

    let missing = packages_without_license(&root).unwrap();
    assert_eq!(missing, Vec::<String>::new());
}

#[test]
fn publish_array_and_missing_version_are_treated_as_unpublishable() {
    let root = git_fixture("publish-shapes");

    // No `version` at all: Cargo cannot publish this regardless of
    // `publish`'s value, so it is not checked -- carries no license and
    // must not appear as missing.
    write(
        &root,
        "crates/no-version/Cargo.toml",
        "[package]\nname = \"no-version\"\n",
    );

    // `publish = []` (no registries) is Cargo's other spelling of
    // unpublishable, distinct from the plain boolean form.
    write(
        &root,
        "crates/empty-registries/Cargo.toml",
        "[package]\nname = \"empty-registries\"\nversion = \"0.1.0\"\npublish = []\n",
    );

    // A non-empty registry list IS publishable (to that registry), so a
    // missing license here must still be reported.
    write(
        &root,
        "crates/named-registry/Cargo.toml",
        "[package]\nname = \"named-registry\"\nversion = \"0.1.0\"\npublish = [\"internal\"]\n",
    );

    let missing = packages_without_license(&root).unwrap();
    assert_eq!(missing, ["crates/named-registry/Cargo.toml"]);
}

#[test]
fn only_touched_files_fail_until_strict() {
    let root = git_fixture("touched");
    write(&root, "src/old.rs", "fn old() {}\n");
    write(
        &root,
        "src/headed.rs",
        &format!("{HEADER}fn headed() {{}}\n"),
    );
    commit(&root, "base");
    git(&root, &["branch", "base"]);

    write(&root, "src/new.rs", "fn new() {}\n");
    write(&root, "src/edited_generated.rs", "fn g() {}\n");
    write(
        &root,
        crate::license_gate::exclusions::MANIFEST,
        "[[exclude]]\nglob = \"src/*_generated.rs\"\nkind = \"generated\"\nreason = \"test\"\n",
    );
    write(
        &root,
        "crates/a/Cargo.toml",
        "[package]\nname = \"a\"\nversion = \"0.1.0\"\n",
    );
    write(
        &root,
        "crates/b/Cargo.toml",
        "[package]\nname = \"b\"\nversion = \"0.1.0\"\npublish = false\n",
    );

    let mut options = Options {
        root: root.clone(),
        base: "base".to_owned(),
        strict: false,
    };
    let report = check_license(&options).unwrap();
    assert_eq!(report.touched_missing, ["src/new.rs"]);
    assert_eq!(report.untouched_missing, ["src/old.rs"]);
    assert_eq!(report.excluded, 1);
    assert_eq!(report.packages_without_license, ["crates/a/Cargo.toml"]);
    // The fixture has no LICENSE, so layer 1 fails alongside the touched file.
    assert_eq!(report.failures(&options).len(), 2);

    options.strict = true;
    assert_eq!(report.failures(&options).len(), 4);
}

