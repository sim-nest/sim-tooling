#[test]
fn globs_respect_segments() {
    assert!(glob_matches(
        "src/*_generated.rs",
        "src/opcode_generated.rs"
    ));
    assert!(!glob_matches(
        "src/*_generated.rs",
        "src/nested/opcode_generated.rs"
    ));
    assert!(glob_matches(
        "**/fixtures/**",
        "crates/a/tests/fixtures/x/y.rs"
    ));
    assert!(glob_matches("**/*.rs", "top.rs"));
    assert!(glob_matches("src/?.rs", "src/a.rs"));
    assert!(!glob_matches("src/?.rs", "src/ab.rs"));
}

#[test]
fn exclusion_manifest_requires_known_kind_and_reason() {
    let ok =
        "[[exclude]]\nglob = \"src/*_generated.rs\"\nkind = \"generated\"\nreason = \"build.rs\"\n";
    assert!(Exclusions::parse(ok).unwrap().matches("src/a_generated.rs"));

    let bad_kind = ok.replace("\"generated\"", "\"vendored\"");
    assert!(
        Exclusions::parse(&bad_kind)
            .unwrap_err()
            .contains("kind must be one of")
    );

    let empty_reason = ok.replace("\"build.rs\"", "\" \"");
    assert!(
        Exclusions::parse(&empty_reason)
            .unwrap_err()
            .contains("reason is empty")
    );

    let unknown_key = format!("{ok}owner = \"x\"\n");
    assert!(Exclusions::parse(&unknown_key).is_err());
}

