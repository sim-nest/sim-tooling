#[test]
fn classifies_notice_generated_other_and_missing() {
    assert_eq!(classify(&format!("{HEADER}fn f() {{}}\n")), Notice::Present);
    assert_eq!(
        classify(&format!("#!/usr/bin/env rust-script\n{HEADER}")),
        Notice::Present
    );
    assert_eq!(classify("// @generated by build.rs\n"), Notice::Generated);
    assert_eq!(
        classify("// SPDX-License-Identifier: MIT OR Apache-2.0\n"),
        Notice::OtherLicense
    );
    assert_eq!(classify("//! Crate docs.\nfn f() {}\n"), Notice::Missing);
}

#[test]
fn a_dual_license_expression_naming_mpl_is_not_the_pure_mpl_notice() {
    // The exact notice text is a prefix of this line; a plain substring
    // match would wrongly accept a different, dual-license expression as
    // the pure single-license notice this gate requires.
    assert_eq!(
        classify("// SPDX-License-Identifier: MPL-2.0 OR MIT\n"),
        Notice::OtherLicense
    );
}

#[test]
fn the_notice_text_quoted_mid_line_is_not_a_notice() {
    assert_eq!(
        classify("let x = \"SPDX-License-Identifier: MPL-2.0\";\n"),
        Notice::Missing
    );
    assert_eq!(
        classify("// see @generated markers in the sibling module\n"),
        Notice::Missing
    );
    // A line that IS the exact notice text is still not a real declaration
    // when it isn't itself a `//` comment -- e.g. one line of a multi-line
    // raw string literal that happens to hold that exact text.
    assert_eq!(
        classify("let s = r#\"\nSPDX-License-Identifier: MPL-2.0\n\"#;\n"),
        Notice::Missing
    );
    // The same, but the embedded line ALSO happens to start with `//` after
    // trimming (a fixture that itself contains comment-shaped text) --
    // still inside the raw string, so still not a real declaration.
    assert_eq!(
        classify("let s = r#\"\n// SPDX-License-Identifier: MPL-2.0\n\"#;\n"),
        Notice::Missing
    );
    assert_eq!(
        classify("let s = r#\"\n// @generated by nothing real\n\"#;\nfn f() {}\n"),
        Notice::Missing
    );
    // A raw string that opens and closes matters for hash-count matching:
    // an inner `"#` with the wrong hash count must not be treated as the
    // close, and a real notice AFTER the string genuinely closes is still
    // found.
    assert_eq!(
        classify(&format!(
            "let s = r##\"\n// {NOTICE}\n\"#\nstill inside\n\"##;\n{HEADER}"
        )),
        Notice::Present
    );
    // A raw string that opens AND closes on the SAME line must not leave
    // the tracker stuck "open" for the rest of the file -- a real notice
    // on a later line must still be found.
    assert_eq!(
        classify(&format!("let _ = r\"x\";\n{HEADER}")),
        Notice::Present
    );
    // A close immediately followed by another open on the same line must
    // pick up the second opener, not lose it.
    assert_eq!(
        classify("let _ = r\"a\"; let _ = r#\"\n// SPDX-License-Identifier: MPL-2.0\n\"#;\n"),
        Notice::Missing
    );
    // Byte and C raw-string prefix forms are recognized too, not just the
    // plain `r` form -- content-shaped text inside either must not count.
    assert_eq!(
        classify("let s = br#\"\n// SPDX-License-Identifier: MPL-2.0\n\"#;\n"),
        Notice::Missing
    );
    assert_eq!(
        classify("let s = cr#\"\n// SPDX-License-Identifier: MPL-2.0\n\"#;\n"),
        Notice::Missing
    );
    // A `//` line comment consumes the rest of ITS OWN line in real Rust,
    // so text after it that merely LOOKS like a raw-string opener (e.g.
    // documentation mentioning the syntax) must not be mistaken for a real
    // one -- doing so would make the tracker think a raw string is open
    // and hide a genuine notice on a later line, an ordinary false
    // negative on honest, well-commented code, not adversarial input.
    assert_eq!(
        classify(&format!("//! The raw-string opener is `r#\"`.\n{HEADER}")),
        Notice::Present
    );
    assert_eq!(
        classify("// see br#\"...\"# for byte raw strings\nfn f() {}\n"),
        Notice::Missing
    );
}

