/// Summary of a `repo-contract` run.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct RepoContractReport {
    /// Number of workspace packages described.
    pub packages: usize,
    /// Number of generated contract artifacts updated.
    pub artifacts_changed: usize,
}

/// Generates the per-repo contract files for the current repository; with
/// `check` true it instead verifies they are current and fails when they are
/// stale. Returns the run summary.
pub fn repo_contract(check: bool) -> Result<RepoContractReport, String> {
    let repo = find_repo_root(&std::env::current_dir().map_err(display_io)?)?;
    repo_contract_for_repo(check, &repo)
}

pub(crate) fn repo_contract_for_repo(
    check: bool,
    repo: &Path,
) -> Result<RepoContractReport, String> {
    let repo = repo.canonicalize().map_err(display_io)?;
    let artifacts = contract_artifacts(&repo)?;
    let package_count = artifacts.package_count;
    let generated_dir = repo.join("docs/generated");
    if !check {
        fs::create_dir_all(&generated_dir).map_err(display_io)?;
    }

    let mut report = RepoContractReport {
        packages: package_count,
        artifacts_changed: 0,
    };
    for (name, content) in artifacts.files {
        if name == "sim-index-fragment.claims.sx" {
            continue;
        }
        write_or_check(&generated_dir.join(name), &content, check, &mut report)?;
    }
    Ok(report)
}

pub(crate) struct ContractArtifacts {
    pub(crate) package_count: usize,
    pub(crate) files: BTreeMap<&'static str, String>,
}

pub(crate) fn contract_artifacts(repo: &Path) -> Result<ContractArtifacts, String> {
    contract_artifacts_observed(repo, &|| {})
}

/// Builds every contract artifact from one measured snapshot: the inputs the
/// provenance hash binds are measured again after every projection has read
/// them (`after_projections` runs in between), and any change refuses the run.
fn contract_artifacts_observed(
    repo: &Path,
    after_projections: &dyn Fn(),
) -> Result<ContractArtifacts, String> {
    let repo = repo.canonicalize().map_err(display_io)?;
    let repo = repo.as_path();
    let contract = contract_packages(repo)?;
    let metadata = &contract.metadata;
    let workspace_names = workspace_package_names(metadata)?;
    let cut = crate::repo_contract_cut::load_or_derive_split_cut(repo, &workspace_names)?;
    let packages = workspace_packages(repo, metadata, &cut)?;
    validate_cut(&packages, &cut)?;

    let package_groups = packages
        .iter()
        .map(|package| (package.name.clone(), package.group.clone()))
        .collect::<BTreeMap<_, _>>();
    let citizens = citizen_classes(repo);
    let exemptions = non_citizen_exemptions(repo);
    let recipes = recipe_books(repo, &package_groups);
    let cards = card_index(repo, &package_groups);
    let provenance = provenance(repo, metadata)?;
    let index_fragment = index_fragment::artifact(repo, &packages, &cards)?;
    let mut files = artifacts(ArtifactInputs {
        packages: &packages,
        cut: &cut,
        citizens: &citizens,
        exemptions: &exemptions,
        recipes: &recipes,
        cards: &cards,
        provenance: &provenance,
        index_fragment: &index_fragment,
        exclusions: &contract
            .exclusions
            .iter()
            .map(|entry| entry.projection())
            .collect::<Vec<_>>(),
    })?;
    files.insert(
        "sim-index-fragment.claims.sx",
        fragment_certificate_artifact(&index_fragment)?,
    );
    after_projections();
    ensure_inputs_unchanged(repo, &provenance)?;
    path_guard::ensure_repository_local(repo, &files)?;

    Ok(ContractArtifacts {
        package_count: packages.len(),
        files,
    })
}

/// Refuses the run when the inputs bound by the provenance workspace hash
/// changed while the projections were reading them.
fn ensure_inputs_unchanged(repo: &Path, provenance: &Value) -> Result<(), String> {
    let (paths, hash) = measure_inputs(repo)?;
    if provenance["workspace_hash"].as_str() != Some(hash.as_str())
        || provenance["workspace_hash_inputs"] != json!(paths)
    {
        return Err(
            "repository inputs changed during generation; the artifacts would not match their \
             recorded workspace hash, so none were produced"
                .to_owned(),
        );
    }
    Ok(())
}

fn fragment_certificate_artifact(fragment: &str) -> Result<String, String> {
    let doc = IndexCodec
        .decode_fragment(IndexForm::Sx, fragment)
        .map_err(|err| format!("decode generated index fragment for claims: {err}"))?;
    let projection = VaultProjection::project_fragment(&doc)
        .map_err(|err| format!("certify generated index fragment: {err}"))?;
    let certificate = projection.certificate();
    let claims = certificate.local_claims();
    if !claims.is_closed() {
        return Err("generated fragment claim certificate did not close".to_owned());
    }
    let mut out = format!(
        "(fragment-certificate [schema {:?}] [generated-by {:?}] [visibility {:?}] [row-count {}] [claims (\n",
        certificate.metadata().schema,
        certificate.metadata().generated_by,
        certificate.metadata().visibility,
        claims.primary().len()
    );
    for (row, site) in claims.primary() {
        out.push_str(&format!(
            "  (primary [row {:?}] [note {:?}] [section {:?}])\n",
            row.diagnostic_key(),
            site.note.as_str(),
            site.section
        ));
    }
    out.push_str(")])\n");
    Ok(out)
}

fn write_or_check(
    path: &Path,
    expected: &str,
    check: bool,
    report: &mut RepoContractReport,
) -> Result<(), String> {
    let current = fs::read_to_string(path).unwrap_or_default();
    if current == expected {
        return Ok(());
    }
    if check {
        return Err(format!(
            "{} is stale; run `cargo run -p xtask -- repo-contract`",
            path.display()
        ));
    }
    fs::write(path, expected).map_err(display_io)?;
    report.artifacts_changed += 1;
    Ok(())
}

